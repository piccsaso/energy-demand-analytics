"""Run: python run.py --demo, or --input a documented real-data CSV."""
import argparse
import csv
from datetime import datetime, timedelta, timezone
import html
import json
import math
from pathlib import Path
import random
from src.energy import load_csv, build_database, correlation

ROOT = Path(__file__).resolve().parent


def generate_demo(path):
    rng = random.Random(42)
    with path.open('w', newline='', encoding='utf-8') as f:
        writer = csv.writer(f)
        writer.writerow(['timestamp', 'demand_mw', 'temperature_c'])
        start = datetime(2025, 1, 1, tzinfo=timezone.utc)
        for i in range(24*14):
            stamp = start + timedelta(hours=i)
            temp = -3 + 5*math.sin(i/37) + rng.gauss(0,1)
            demand = 16000 + 1800*math.cos((stamp.hour-22)*math.pi/12) + 90*abs(temp-15) + rng.gauss(0,180)
            writer.writerow([stamp.isoformat(), round(demand,2), round(temp,2)])


def query_to_csv(conn, sql_name, target):
    result = conn.execute((ROOT/'sql'/sql_name).read_text(encoding='utf-8'))
    rows = result.fetchall()
    with target.open('w', newline='', encoding='utf-8') as f:
        writer = csv.writer(f)
        writer.writerow([c[0] for c in result.description])
        writer.writerows(rows)
    return rows


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument('--demo', action='store_true')
    group.add_argument('--input', type=Path)
    parser.add_argument('--source', help='Source URL or dataset identifier, required for real inputs')
    args = parser.parse_args()
    if args.input and not args.source:
        parser.error('--input requires --source for provenance')
    out = ROOT/'reports'/'generated'
    out.mkdir(parents=True, exist_ok=True)
    path = args.input
    if args.demo:
        path = out/'synthetic_demand.csv'
        generate_demo(path)
    rows, checks = load_csv(path)
    with build_database(rows, out/'energy.sqlite') as conn:
        hourly = query_to_csv(conn, 'hourly_profile.sql', out/'hourly_profile.csv')
        query_to_csv(conn, 'daily_summary.sql', out/'daily_summary.csv')
    peak = max(rows, key=lambda r:r[1])
    summary = {**checks, 'mode': 'synthetic demo' if args.demo else 'user-supplied data',
               'source': 'generated by run.py, seed 42' if args.demo else args.source,
               'timezone': 'UTC', 'start': rows[0][0], 'end': rows[-1][0],
               'peak_demand_mw': peak[1], 'peak_timestamp': peak[0],
               'temperature_demand_pearson_r': correlation(rows)}
    (out/'summary.json').write_text(json.dumps(summary, indent=2), encoding='utf-8')
    maximum = max(r[2] for r in hourly)
    bars = ''.join(f'<rect x="{48+i*27}" y="{280-r[2]/maximum*210:.1f}" width="18" height="{r[2]/maximum*210:.1f}" fill="#258b9a"/><text x="{48+i*27}" y="302">{r[0]}</text>' for i,r in enumerate(hourly))
    label = 'SYNTHETIC DEMO - not Ontario observations' if args.demo else 'User-supplied observations - verify coverage and source'
    page = f'''<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width"><title>Energy demand analysis</title>
<style>body{{font:16px system-ui;max-width:1000px;margin:40px auto;padding:0 20px;color:#173449;background:#f4f7fa}}article{{background:white;padding:24px;border-radius:12px;margin:20px 0}}svg{{width:100%;height:auto}}text{{font:11px system-ui}}pre{{white-space:pre-wrap}}</style>
<h1>Energy demand analysis</h1><p><strong>{label}</strong></p><article><h2>Average demand by UTC hour</h2><p>Bar heights start at zero. Maximum hourly mean: {maximum:,.0f} MW. Times use UTC, not Ontario local time.</p>
<svg viewBox="0 0 730 330" role="img" aria-label="Average electricity demand in megawatts by UTC hour"><line x1="40" y1="280" x2="710" y2="280" stroke="#173449"/>{bars}<text x="40" y="320">UTC hour</text></svg></article>
<article><h2>Data checks and summary</h2><pre>{html.escape(json.dumps(summary, indent=2))}</pre></article>
<article><h2>Interpretation</h2><p>The peak in this input is {peak[1]:,.0f} MW at {html.escape(peak[0])}. Missing hours: {checks['missing_hours']}. Incomplete coverage can distort daily and hourly comparisons.</p>
<p>Temperature correlation is descriptive, not causal. Heating and cooling relationships can be nonlinear. Demo patterns were deliberately generated and are not findings about Ontario.</p></article></html>'''
    (out/'dashboard.html').write_text(page, encoding='utf-8')
    print(json.dumps(summary, indent=2))
    print('Open reports/generated/dashboard.html; CSV summaries can be imported into Power BI.')


if __name__ == '__main__':
    main()
